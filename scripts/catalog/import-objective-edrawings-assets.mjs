import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import puppeteer from 'puppeteer-core';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DEFAULT_OUT_DIR = join(ROOT, 'public', 'catalog', 'mechanical', 'objectives');
const DEFAULT_MANIFEST = join(ROOT, 'src', 'catalog', 'generatedMechanicalVisualAssets.ts');
const DEFAULT_CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';

function argValue(flag, fallback) {
    const index = process.argv.indexOf(flag);
    return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

function argValues(flag) {
    const values = [];
    for (let i = 2; i < process.argv.length; i++) {
        if (process.argv[i] === flag && process.argv[i + 1]) values.push(process.argv[++i]);
    }
    return values;
}

function hasFlag(flag) {
    return process.argv.includes(flag);
}

function usage() {
    console.log(`Usage: bun scripts/catalog/import-objective-edrawings-assets.mjs [options]

Extracts browser-loadable eDrawing/HOOPS visual assets for catalog parts
and writes the mechanical visual manifest.

Options:
  --sku SKU       Limit to one or more SKUs. When set, any catalog component type is eligible.
  --component-type TYPE
                  Limit to a catalog component type. Defaults to objective when no SKU is set.
  --limit N       Import at most N matching catalog parts
  --out-dir PATH  Output static mesh directory
  --manifest PATH Generated TypeScript manifest path
  --chrome PATH   Chrome executable path
  --force         Re-import existing objective assets
  --help          Show this help
`);
}

function sanitizeSku(sku) {
    return sku.trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

function rounded(value) {
    return Math.round(value * 1e8) / 1e8;
}

function outputAssetPath(outDir, part) {
    return join(outDir, `${sanitizeSku(part.sku)}.edrawings.json`);
}

function publicUrlForAsset(assetPath) {
    const publicRoot = resolve(join(ROOT, 'public'));
    const relative = resolve(assetPath).slice(publicRoot.length).replace(/\\/g, '/');
    if (!relative.startsWith('/')) {
        throw new Error(`Asset output must be inside public/: ${assetPath}`);
    }
    return relative;
}

function candidateHtmlUrl(fileUrl) {
    const parsed = new URL(fileUrl);
    const ext = extname(parsed.pathname).toLowerCase();
    if (!ext) return null;
    parsed.pathname = parsed.pathname.slice(0, -ext.length) + '.html';
    return parsed.toString();
}

function edrawingsUrlCandidates(part) {
    const scoredFiles = part.files
        .filter(file => {
            if (file.role === 'mechanicalModel' && (file.kind === 'step' || file.kind === 'solidworks')) return true;
            if (file.role === 'datasheet' && file.kind === 'pdf') return true;
            if (file.role === 'drawing' && file.kind === 'dxf') return true;
            return false;
        })
        .map(file => {
            let score = 10;
            if (file.kind === 'step') score = 0;
            else if (file.kind === 'solidworks') score = 1;
            else if (file.kind === 'pdf') score = 2;
            else if (file.kind === 'dxf') score = 3;
            return { file, score };
        })
        .sort((a, b) => a.score - b.score);

    const urls = [];
    const seen = new Set();
    for (const { file } of scoredFiles) {
        const url = candidateHtmlUrl(file.url);
        if (!url || seen.has(url)) continue;
        seen.add(url);
        urls.push(url);
    }
    return urls;
}

function manifestSource(assets) {
    const rows = Object.fromEntries(assets.map(asset => [asset.partId, asset]));
    return `import type { CatalogMechanicalVisualAsset } from './mechanicalVisualAssets';

// Generated by scripts/catalog/import-objective-edrawings-assets.mjs.
// The app renders these browser-loadable eDrawing mesh/line assets; STEP and
// SolidWorks URLs in the catalog remain source CAD.
export const GENERATED_MECHANICAL_VISUAL_ASSETS: Record<string, CatalogMechanicalVisualAsset> = ${JSON.stringify(rows, null, 4)};
`;
}

function readExistingManifest(manifestPath) {
    if (!existsSync(manifestPath)) return [];
    const text = readFileSync(manifestPath, 'utf8');
    const match = text.match(/=\s*(\{[\s\S]*\});?\s*$/);
    if (!match) return [];
    try {
        return Object.values(JSON.parse(match[1]));
    } catch {
        return [];
    }
}

async function loadCatalogParts() {
    if (!process.versions.bun) {
        throw new Error('This script imports TypeScript catalog modules; run it with bun.');
    }
    const modulePath = new URL('../../src/catalog/catalog.ts', import.meta.url).href;
    const { CATALOG_PARTS } = await import(modulePath);
    return CATALOG_PARTS;
}

async function newExtractionPage(browser) {
    const page = await browser.newPage();
    page.setDefaultTimeout(90_000);
    await page.evaluateOnNewDocument(() => {
        window.__edwFindViewer = function () {
            if (window.__edwViewer?.HCViewer?.model) return window.__edwViewer;
            for (const key of Object.getOwnPropertyNames(window)) {
                try {
                    const value = window[key];
                    if (value?.HCViewer?.model) return value;
                } catch {
                    // Some globals throw on access.
                }
            }
            return null;
        };
        function installHook() {
            const jq = window.jQuery || window.$;
            if (!jq || !jq.fn || jq.__edwAssetCaptureInstalled) return;
            const originalTrigger = jq.fn.trigger;
            jq.fn.trigger = function (...args) {
                const type = typeof args[0] === 'string' ? args[0] : args[0]?.type;
                if (String(type).includes('ModelDataLoadComplete')) window.__edwViewer = args[1];
                return originalTrigger.apply(this, args);
            };
            jq.__edwAssetCaptureInstalled = true;
        }
        window.__edwHookInterval = window.setInterval(installHook, 10);
        installHook();
    });
    return page;
}

async function extractAsset(browser, part, sourceUrl) {
    const page = await newExtractionPage(browser);
    try {
        await page.goto(sourceUrl, { waitUntil: 'domcontentloaded', timeout: 90_000 });
        await page.waitForFunction(() => {
            window.__edwViewer = window.__edwFindViewer?.() ?? window.__edwViewer;
            return Boolean(window.__edwViewer?.HCViewer?.model);
        }, {
            timeout: 90_000,
            polling: 250,
        });
        await new Promise(resolve => setTimeout(resolve, 6_000));

        return await page.evaluate(({ sku, sourceUrl }) => {
            const round = value => Math.round(value * 1e8) / 1e8;
            const serializeColor = color => {
                const value = typeof color?.toJson === 'function' ? color.toJson() : color;
                return {
                    r: Math.round(value?.r ?? 0),
                    g: Math.round(value?.g ?? 0),
                    b: Math.round(value?.b ?? 0),
                };
            };
            const safeColor = async (fallback, read) => {
                try {
                    return serializeColor(await read());
                } catch {
                    return fallback;
                }
            };
            const safeOpacity = async read => {
                try {
                    const opacity = await read();
                    return Number.isFinite(opacity) ? opacity : 1;
                } catch {
                    return 1;
                }
            };
            const serializeBox = box => {
                if (!box || typeof box.toJson !== 'function') return null;
                const json = box.toJson();
                return {
                    min: { x: round(json.min.x), y: round(json.min.y), z: round(json.min.z) },
                    max: { x: round(json.max.x), y: round(json.max.y), z: round(json.max.z) },
                };
            };
            const extractVertexPositions = stream => {
                const positions = [];
                if (!stream || typeof stream.iterate !== 'function') return positions;
                const iterator = stream.iterate(true);
                for (;;) {
                    const next = iterator.next();
                    if (next.done) break;
                    const vertex = next.value;
                    if (!vertex?.position) continue;
                    positions.push(round(vertex.position[0]), round(vertex.position[1]), round(vertex.position[2]));
                }
                return positions;
            };
            const extractGeometry = mesh => {
                const positions = [];
                const normals = [];
                const iterator = mesh.faces.iterate(true);
                for (;;) {
                    const next = iterator.next();
                    if (next.done) break;
                    const vertex = next.value;
                    if (!vertex?.position) continue;
                    positions.push(round(vertex.position[0]), round(vertex.position[1]), round(vertex.position[2]));
                    if (vertex.normal) {
                        normals.push(round(vertex.normal[0]), round(vertex.normal[1]), round(vertex.normal[2]));
                    }
                }
                return {
                    positions,
                    normals: normals.length === positions.length ? normals : undefined,
                    lines: extractVertexPositions(mesh.lines),
                };
            };

            const viewer = window.__edwViewer;
            const model = viewer.HCViewer.model;
            const root = model.getAbsoluteRootNode();
            const queue = [root];
            const seen = new Set();
            const nodes = [];
            while (queue.length && nodes.length < 5_000) {
                const id = queue.shift();
                if (seen.has(id)) continue;
                seen.add(id);
                const children = model.getNodeChildren(id) || [];
                nodes.push({
                    id,
                    name: model.getNodeName(id),
                    type: model.getNodeType(id),
                    childCount: children.length,
                });
                for (const child of children) queue.push(child);
            }

            return Promise.all(nodes.filter(node => node.type === 3 && node.childCount === 0).map(async node => {
                try {
                    const opacity = await safeOpacity(async () => (await model.getNodesEffectiveOpacity([node.id]))[0]);
                    if (opacity <= 0) return null;
                    const mesh = await model.getNodeMeshData(node.id);
                    if (!mesh?.faces?.vertexCount) return null;
                    const color = await safeColor({ r: 230, g: 235, b: 235 }, async () => await model.getNodeEffectiveFaceColor(node.id));
                    const lineColor = typeof model.getNodeEffectiveLineColor === 'function'
                        ? await safeColor({ r: 0, g: 0, b: 0 }, async () => await model.getNodeEffectiveLineColor(node.id))
                        : { r: 0, g: 0, b: 0 };
                    const bounding = serializeBox(await model.getNodesBounding([node.id]));
                    const geometry = extractGeometry(mesh);
                    if (geometry.positions.length < 9) return null;
                    return {
                        id: node.id,
                        name: node.name,
                        color,
                        lineColor,
                        sourceOpacity: opacity,
                        bounding,
                        vertexCount: geometry.positions.length / 3,
                        positions: geometry.positions,
                        normals: geometry.normals,
                        lines: geometry.lines.length >= 6 ? geometry.lines : undefined,
                    };
                } catch {
                    return null;
                }
            })).then(bodies => ({
                schema: 'edrawings-hoops-body-mesh-v1',
                sku,
                sourceUrl,
                sourceUnits: 'm',
                generatedAt: new Date().toISOString(),
                bodies: bodies.filter(Boolean),
            }));
        }, { sku: part.sku, sourceUrl });
    } finally {
        await page.close();
    }
}

function scrubAsset(asset) {
    for (const body of asset.bodies) {
        body.positions = body.positions.map(rounded);
        if (body.normals) body.normals = body.normals.map(rounded);
        if (body.lines) body.lines = body.lines.map(rounded);
    }
    return asset;
}

function readExistingAsset(assetPath) {
    if (!existsSync(assetPath)) return null;
    try {
        return JSON.parse(readFileSync(assetPath, 'utf8'));
    } catch {
        return null;
    }
}

async function main() {
    if (hasFlag('--help')) {
        usage();
        return;
    }

    const outDir = resolve(argValue('--out-dir', DEFAULT_OUT_DIR));
    const manifestPath = resolve(argValue('--manifest', DEFAULT_MANIFEST));
    const chrome = argValue('--chrome', DEFAULT_CHROME);
    const force = hasFlag('--force');
    const requestedSkus = new Set(argValues('--sku').map(sku => sku.toUpperCase()));
    const requestedTypes = new Set(argValues('--component-type'));
    const limitValue = Number.parseInt(argValue('--limit', '0'), 10);
    const limit = Number.isFinite(limitValue) && limitValue > 0 ? limitValue : Number.POSITIVE_INFINITY;

    mkdirSync(outDir, { recursive: true });
    mkdirSync(dirname(manifestPath), { recursive: true });

    const parts = await loadCatalogParts();
    const catalogParts = parts
        .filter(part => requestedSkus.size > 0
            ? requestedSkus.has(part.sku.toUpperCase())
            : (requestedTypes.size > 0 ? requestedTypes.has(part.componentType) : part.componentType === 'objective'))
        .filter(part => requestedSkus.size === 0 || requestedSkus.has(part.sku.toUpperCase()))
        .filter(part => edrawingsUrlCandidates(part).length > 0)
        .slice(0, limit);

    const existingAssets = readExistingManifest(manifestPath);
    const assetsByPartId = new Map(existingAssets.map(asset => [asset.partId, asset]));
    const browser = await puppeteer.launch({
        executablePath: chrome,
        headless: 'new',
        args: [
            '--no-sandbox',
            '--disable-dev-shm-usage',
            '--disable-gpu',
            '--ignore-certificate-errors',
        ],
    });

    const imported = [];
    const failures = [];
    try {
        for (const part of catalogParts) {
            const assetPath = outputAssetPath(outDir, part);
            const existingAsset = readExistingAsset(assetPath);
            if (!force && existingAsset?.bodies?.length) {
                const asset = {
                    partId: part.id,
                    sku: part.sku,
                    format: 'edrawings-json',
                    url: publicUrlForAsset(assetPath),
                    sourceUrl: existingAsset.sourceUrl ?? edrawingsUrlCandidates(part)[0],
                    units: 'mm',
                    generatedAt: existingAsset.generatedAt ?? new Date().toISOString(),
                };
                assetsByPartId.set(part.id, asset);
                imported.push({ part, reused: true, sourceUrl: asset.sourceUrl, bodies: existingAsset.bodies.length });
                console.log(`${part.sku}: reused ${asset.url}`);
                continue;
            }

            let success = null;
            const errors = [];
            for (const sourceUrl of edrawingsUrlCandidates(part)) {
                try {
                    console.log(`${part.sku}: trying ${sourceUrl}`);
                    const asset = scrubAsset(await extractAsset(browser, part, sourceUrl));
                    if (asset.bodies.length === 0) throw new Error('No visible body meshes extracted');
                    writeFileSync(assetPath, `${JSON.stringify(asset)}\n`);
                    success = { asset, sourceUrl };
                    break;
                } catch (error) {
                    errors.push(`${sourceUrl}: ${error instanceof Error ? error.message : String(error)}`);
                    console.warn(`${part.sku}: failed ${sourceUrl}`);
                }
            }

            if (!success) {
                failures.push({ sku: part.sku, errors });
                continue;
            }

            const manifestAsset = {
                partId: part.id,
                sku: part.sku,
                format: 'edrawings-json',
                url: publicUrlForAsset(assetPath),
                sourceUrl: success.sourceUrl,
                units: 'mm',
                generatedAt: success.asset.generatedAt,
            };
            assetsByPartId.set(part.id, manifestAsset);
            imported.push({ part, reused: false, sourceUrl: success.sourceUrl, bodies: success.asset.bodies.length });
            console.log(`${part.sku}: wrote ${success.asset.bodies.length} body mesh(es)`);
        }
    } finally {
        await browser.close();
    }

    const allAssets = [...assetsByPartId.values()].sort((a, b) => a.sku.localeCompare(b.sku));
    writeFileSync(manifestPath, manifestSource(allAssets));
    console.log(`Wrote ${allAssets.length} manifest entry(s). Imported/reused ${imported.length}/${catalogParts.length} mechanical asset(s).`);
    if (failures.length > 0) {
        console.log(`Failed ${failures.length} objective asset(s):`);
        for (const failure of failures) {
            console.log(`- ${failure.sku}`);
            for (const error of failure.errors) console.log(`  ${error}`);
        }
    }
}

main().catch(error => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
});
