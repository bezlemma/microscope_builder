// Re-import exact asphere prescriptions from the vendor ZMX files recorded in
// each part's provenance. The optics importer used to map Zemax EVENASPH
// PARM p to the r^(2p+2) coefficient instead of r^(2p); the baked arrays were
// later shifted back into place (fix-asphere-coefficient-shift.mjs), but that
// repair could not recover the PARM 7 (A14) terms the original import had
// discarded. This script re-runs the (now correct) importer against the real
// vendor files for every part that carries asphere data.
//
// Run with: bun scripts/catalog/reimport-zemax-asphere-prescriptions.mjs [--dry-run]
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const targetPath = path.join(root, 'src/catalog/thorlabsGeneratedCatalog.ts');
const dryRun = process.argv.includes('--dry-run');
const CONCURRENCY = 6;

const { THORLABS_GENERATED_CATALOG } = await import(pathToFileURL(targetPath).href);
const { enrichCatalogPartWithPrescriptionText } = await import(
    pathToFileURL(path.join(root, 'src/catalog/catalogPrescriptionEnrichment.ts')).href
);

function zemaxUrl(part) {
    return part.provenance?.find(entry => entry.source === 'zemax' && /\.zmx(\?|$)/i.test(entry.url ?? ''))?.url;
}

function hasAsphereData(part) {
    const normalized = part.normalized ?? {};
    if (normalized.kind === 'asphericLens') return true;
    const terms = [...(normalized.a1 ?? []), ...(normalized.a2 ?? [])];
    return terms.some(value => value !== 0);
}

function fileNameFromUrl(url) {
    const clean = url.split(/[?#]/)[0];
    return clean.split('/').pop() ?? 'prescription.zmx';
}

const parts = [...THORLABS_GENERATED_CATALOG];
const targets = parts
    .map((part, index) => ({ part, index, url: zemaxUrl(part) }))
    .filter(({ part, url }) => url && hasAsphereData(part));
console.log(`${targets.length} of ${parts.length} parts carry asphere data with a ZMX provenance URL.`);

const results = { updated: 0, unchanged: 0, failed: 0 };
const failures = [];
let cursor = 0;

async function worker() {
    while (cursor < targets.length) {
        const { part, index, url } = targets[cursor++];
        try {
            const response = await fetch(url);
            if (!response.ok) throw new Error(`HTTP ${response.status}`);
            const bytes = new Uint8Array(await response.arrayBuffer());
            // Thorlabs ZMX files are UTF-16LE with BOM; fall back to UTF-8.
            const text = bytes[0] === 0xff && bytes[1] === 0xfe
                ? new TextDecoder('utf-16le').decode(bytes.subarray(2))
                : new TextDecoder('utf-8').decode(bytes);

            // The enricher appends a fresh zemax provenance entry; drop stale ones
            // so re-runs don't accumulate duplicates.
            const stripped = {
                ...part,
                provenance: (part.provenance ?? []).filter(entry => entry.source !== 'zemax'),
            };
            const enriched = enrichCatalogPartWithPrescriptionText(stripped, text, fileNameFromUrl(url), url);

            if (JSON.stringify(enriched.normalized) === JSON.stringify(part.normalized)) {
                results.unchanged++;
                // Keep the refreshed provenance anyway so retrievedAt is honest.
            } else {
                results.updated++;
            }
            parts[index] = enriched;
        } catch (error) {
            results.failed++;
            failures.push({ sku: part.sku, url, error: error instanceof Error ? error.message : String(error) });
        }
    }
}

await Promise.all(Array.from({ length: Math.min(CONCURRENCY, targets.length) }, () => worker()));

console.log(`normalized params updated: ${results.updated}, unchanged: ${results.unchanged}, failed: ${results.failed}`);
for (const failure of failures) console.warn(`  FAILED ${failure.sku}: ${failure.error} (${failure.url})`);

if (dryRun) {
    console.log('Dry run — file not written.');
    process.exit(0);
}

// Same module shape as scripts/catalog/enrich-thorlabs-prices.mjs.
const catalogJson = JSON.stringify(parts);
const catalogChunks = catalogJson.match(/.{1,24000}/g) ?? [''];
const moduleText = [
    "import type { CatalogPart } from './types';",
    '',
    '// Generated by scripts/catalog/enrich-thorlabs-prices.mjs.',
    '// Prices are cached vendor snapshots and may change at the source.',
    'const THORLABS_GENERATED_CATALOG_JSON = [',
    ...catalogChunks.map(chunk => `  ${JSON.stringify(chunk)},`),
    "].join('');",
    '',
    'export const THORLABS_GENERATED_CATALOG = JSON.parse(THORLABS_GENERATED_CATALOG_JSON) as CatalogPart[];',
    '',
].join('\n');

await writeFile(targetPath, moduleText, 'utf8');
console.log(`Wrote ${targetPath}`);
