import { existsSync, readFileSync, statSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const PUBLIC_ROOT = resolve(ROOT, 'public');
const DEFAULT_MANIFEST = resolve(ROOT, 'src', 'catalog', 'generatedMechanicalVisualAssets.ts');
const SIMPLE_COMPONENT_TYPES = new Set([
    'sphericalLens',
    'asphericLens',
    'cylindricalLens',
    'achromatDoublet',
    'prism',
    'mirror',
    'curvedMirror',
    'beamSplitter',
    'polarizingBeamSplitter',
    'dichroic',
    'filter',
]);

function argValue(flag, fallback) {
    const index = process.argv.indexOf(flag);
    return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

function hasFlag(flag) {
    return process.argv.includes(flag);
}

function usage() {
    console.log(`Usage: bun scripts/catalog/prune-mechanical-visual-assets.mjs [options]

Removes generated vendor mechanical meshes for bare/simple optics that the app
can render procedurally. Objectives and cased/mounted parts are kept.

Options:
  --manifest PATH   Generated mechanical visual manifest
  --delete          Delete mesh files and rewrite the manifest. Omit for dry run.
  --help            Show this help
`);
}

function parseManifest(manifestPath) {
    const text = readFileSync(manifestPath, 'utf8');
    const match = text.match(/=\s*(\{[\s\S]*\});?\s*$/);
    if (!match) throw new Error(`Could not parse manifest: ${manifestPath}`);
    return Object.values(JSON.parse(match[1]));
}

function manifestSource(assets) {
    const rows = Object.fromEntries(assets.map(asset => [asset.partId, asset]));
    return `import type { CatalogMechanicalVisualAsset } from './mechanicalVisualAssets';

// Generated by scripts/catalog/build-objective-mechanical-assets.mjs.
// The app renders vendor mechanical assets listed here; STEP URLs in the
// catalog remain source CAD and are converted offline into browser-loadable meshes.
export const GENERATED_MECHANICAL_VISUAL_ASSETS: Record<string, CatalogMechanicalVisualAsset> = ${JSON.stringify(rows, null, 4)};
`;
}

function assetPath(asset) {
    if (!asset.url.startsWith('/')) {
        throw new Error(`Mechanical asset URL must be root-relative: ${asset.url}`);
    }
    const path = resolve(PUBLIC_ROOT, `.${asset.url}`);
    if (path !== PUBLIC_ROOT && !path.startsWith(`${PUBLIC_ROOT}\\`) && !path.startsWith(`${PUBLIC_ROOT}/`)) {
        throw new Error(`Refusing to touch asset outside public/: ${path}`);
    }
    return path;
}

function isMountedOrCased(part) {
    const mounting = String(part.specs.mounting?.value ?? '').trim().toLowerCase();
    if (mounting === 'mounted') return true;
    if (mounting === 'unmounted') return false;
    if (part.specs.threading) return true;

    const text = `${part.title} ${part.categoryPath.join(' ')}`;
    if (/\bunmounted\b/i.test(text)) return false;
    return /\b(mounted|mount|housing|housed|cased|threaded)\b/i.test(text);
}

function shouldKeepAsset(part) {
    if (!part) return false;
    if (part.componentType === 'objective') return true;
    if (!SIMPLE_COMPONENT_TYPES.has(part.componentType)) return true;
    return isMountedOrCased(part);
}

function bytesForAsset(asset) {
    const path = assetPath(asset);
    return existsSync(path) ? statSync(path).size : 0;
}

async function loadCatalogParts() {
    if (!process.versions.bun) {
        throw new Error('This script imports TypeScript catalog modules; run it with bun.');
    }
    const modulePath = new URL('../../src/catalog/catalog.ts', import.meta.url).href;
    const { CATALOG_PARTS } = await import(modulePath);
    return CATALOG_PARTS;
}

function formatMb(bytes) {
    return `${(bytes / 1024 / 1024).toFixed(2)} MB`;
}

async function main() {
    if (hasFlag('--help')) {
        usage();
        return;
    }

    const deleteFiles = hasFlag('--delete');
    const manifestPath = resolve(argValue('--manifest', DEFAULT_MANIFEST));
    const assets = parseManifest(manifestPath);
    const parts = await loadCatalogParts();
    const partsById = new Map(parts.map(part => [part.id, part]));

    const kept = [];
    const pruned = [];
    for (const asset of assets) {
        const part = partsById.get(asset.partId);
        if (shouldKeepAsset(part)) kept.push(asset);
        else pruned.push({ asset, part });
    }

    const prunedBytes = pruned.reduce((sum, { asset }) => sum + bytesForAsset(asset), 0);
    const keptBytes = kept.reduce((sum, asset) => sum + bytesForAsset(asset), 0);
    const byType = new Map();
    for (const { asset, part } of pruned) {
        const type = part?.componentType ?? 'unknown';
        const existing = byType.get(type) ?? { count: 0, bytes: 0 };
        byType.set(type, {
            count: existing.count + 1,
            bytes: existing.bytes + bytesForAsset(asset),
        });
    }

    console.log(`${deleteFiles ? 'Pruning' : 'Dry run'} ${pruned.length}/${assets.length} mechanical visual asset(s).`);
    console.log(`Would remove ${formatMb(prunedBytes)} and keep ${formatMb(keptBytes)} in referenced mesh files.`);
    for (const [type, value] of [...byType.entries()].sort((a, b) => b[1].bytes - a[1].bytes)) {
        console.log(`- ${type}: ${value.count} asset(s), ${formatMb(value.bytes)}`);
    }

    if (!deleteFiles) return;

    for (const { asset } of pruned) {
        const path = assetPath(asset);
        if (existsSync(path)) unlinkSync(path);
    }
    kept.sort((a, b) => a.sku.localeCompare(b.sku));
    writeFileSync(manifestPath, manifestSource(kept));
    console.log(`Wrote ${kept.length} manifest entry(s).`);
}

main().catch(error => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
});
