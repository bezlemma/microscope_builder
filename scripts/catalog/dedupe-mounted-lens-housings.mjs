import { createHash } from 'node:crypto';
import {
    existsSync,
    mkdirSync,
    readFileSync,
    renameSync,
    rmSync,
    statSync,
    unlinkSync,
    writeFileSync,
} from 'node:fs';
import { basename, dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const PUBLIC_ROOT = resolve(ROOT, 'public');
const DEFAULT_MANIFEST = resolve(ROOT, 'src', 'catalog', 'generatedMechanicalVisualAssets.ts');
const SHARED_COMPONENT_DIR = resolve(PUBLIC_ROOT, 'catalog', 'mechanical', 'shared', 'lens-components');
const COMPONENT_FLOAT = 5126;
const COMPONENT_UNSIGNED_SHORT = 5123;
const COMPONENT_UNSIGNED_INT = 5125;

function argValue(flag, fallback) {
    const index = process.argv.indexOf(flag);
    return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

function hasFlag(flag) {
    return process.argv.includes(flag);
}

function usage() {
    console.log(`Usage: bun scripts/catalog/dedupe-mounted-lens-housings.mjs [options]

Splits mounted lens GLB assets into connected geometry components, writes
repeated components once under public/catalog/mechanical/shared/lens-components,
and rewrites each mounted lens asset as a small GLTF file that references the
shared component buffers plus a per-part buffer for unique lens geometry.

Options:
  --apply           Write GLTF/bin assets, delete replaced lens GLBs, and update manifest
  --manifest PATH   Generated mechanical visual manifest
  --keep-glb        Keep the original mounted lens GLBs after --apply
  --help            Show this help
`);
}

function parseManifest(manifestPath) {
    const text = readFileSync(manifestPath, 'utf8');
    const match = text.match(/=\s*(\{[\s\S]*\});?\s*$/);
    if (!match) throw new Error(`Could not parse manifest: ${manifestPath}`);
    return Object.values(JSON.parse(match[1]));
}

function manifestSource(assets) {
    const rows = Object.fromEntries(assets.map(asset => [asset.partId, asset]));
    return `import type { CatalogMechanicalVisualAsset } from './mechanicalVisualAssets';

// Generated by scripts/catalog/build-objective-mechanical-assets.mjs.
// The app renders vendor mechanical assets listed here; STEP URLs in the
// catalog remain source CAD and are converted offline into browser-loadable meshes.
export const GENERATED_MECHANICAL_VISUAL_ASSETS: Record<string, CatalogMechanicalVisualAsset> = ${JSON.stringify(rows, null, 4)};
`;
}

function writeFileReplacingMappedFile(path, text) {
    try {
        writeFileSync(path, text);
        return;
    } catch (error) {
        if (error?.code !== 'UNKNOWN' && error?.code !== 'EPERM' && error?.code !== 'EBUSY') throw error;
    }

    const nextPath = `${path}.new`;
    const backupPath = `${path}.mapped-backup`;
    writeFileSync(nextPath, text);
    if (existsSync(backupPath)) unlinkSync(backupPath);
    renameSync(path, backupPath);
    renameSync(nextPath, path);
    try {
        unlinkSync(backupPath);
    } catch {
        // Windows can briefly hold the old mapped file. The new file is already in place.
    }
}

function assertInside(path, root, label) {
    const resolvedPath = resolve(path);
    const resolvedRoot = resolve(root);
    if (resolvedPath !== resolvedRoot && !resolvedPath.startsWith(`${resolvedRoot}\\`) && !resolvedPath.startsWith(`${resolvedRoot}/`)) {
        throw new Error(`Refusing to touch ${label} outside ${resolvedRoot}: ${resolvedPath}`);
    }
    return resolvedPath;
}

function assetPath(asset) {
    if (!asset.url.startsWith('/')) throw new Error(`Mechanical asset URL must be root-relative: ${asset.url}`);
    return assertInside(resolve(PUBLIC_ROOT, `.${asset.url}`), PUBLIC_ROOT, 'asset');
}

function publicPathToUrl(path) {
    const resolved = assertInside(path, PUBLIC_ROOT, 'asset');
    return `/${relative(PUBLIC_ROOT, resolved).replace(/\\/g, '/')}`;
}

function relativeUri(fromFile, targetFile) {
    return relative(dirname(fromFile), targetFile).replace(/\\/g, '/');
}

function isMountedLensGlbAsset(asset) {
    return (
        asset.format === 'glb' &&
        asset.url.includes('/catalog/mechanical/lenses/') &&
        asset.url.endsWith('.glb')
    );
}

function parseGlb(path) {
    const buffer = readFileSync(path);
    if (buffer.toString('utf8', 0, 4) !== 'glTF') throw new Error(`Not a GLB file: ${path}`);
    let offset = 12;
    let json = null;
    let bin = null;
    while (offset < buffer.length) {
        const chunkLength = buffer.readUInt32LE(offset);
        const chunkType = buffer.readUInt32LE(offset + 4);
        offset += 8;
        const chunk = buffer.subarray(offset, offset + chunkLength);
        offset += chunkLength;
        if (chunkType === 0x4e4f534a) json = JSON.parse(chunk.toString('utf8').trim());
        if (chunkType === 0x004e4942) bin = chunk;
    }
    if (!json || !bin) throw new Error(`GLB is missing JSON or BIN chunks: ${path}`);

    const primitive = json.meshes?.[0]?.primitives?.[0];
    if (
        primitive?.indices == null ||
        primitive?.attributes?.POSITION == null ||
        primitive?.attributes?.NORMAL == null
    ) {
        throw new Error(`GLB must have POSITION, NORMAL, and index accessors: ${path}`);
    }

    const indices = readIndexAccessor(json, bin, primitive.indices);
    const positions = readFloatVec3Accessor(json, bin, primitive.attributes.POSITION);
    const normals = readFloatVec3Accessor(json, bin, primitive.attributes.NORMAL);
    if (positions.length !== normals.length) throw new Error(`Position/normal mismatch: ${path}`);
    return { indices, positions, normals };
}

function accessorView(json, accessorIndex) {
    const accessor = json.accessors[accessorIndex];
    const view = json.bufferViews[accessor.bufferView];
    return {
        accessor,
        byteOffset: (view.byteOffset ?? 0) + (accessor.byteOffset ?? 0),
    };
}

function readIndexAccessor(json, bin, accessorIndex) {
    const { accessor, byteOffset } = accessorView(json, accessorIndex);
    const indices = [];
    for (let index = 0; index < accessor.count; index++) {
        if (accessor.componentType === COMPONENT_UNSIGNED_SHORT) {
            indices.push(bin.readUInt16LE(byteOffset + index * 2));
        } else if (accessor.componentType === COMPONENT_UNSIGNED_INT) {
            indices.push(bin.readUInt32LE(byteOffset + index * 4));
        } else {
            throw new Error(`Unsupported index component type: ${accessor.componentType}`);
        }
    }
    return indices;
}

function readFloatVec3Accessor(json, bin, accessorIndex) {
    const { accessor, byteOffset } = accessorView(json, accessorIndex);
    if (accessor.componentType !== COMPONENT_FLOAT || accessor.type !== 'VEC3') {
        throw new Error(`Expected Float32 VEC3 accessor.`);
    }
    const values = [];
    for (let index = 0; index < accessor.count * 3; index++) {
        values.push(bin.readFloatLE(byteOffset + index * 4));
    }
    return values;
}

function connectedComponents(geometry) {
    const vertexCount = geometry.positions.length / 3;
    const parents = Array.from({ length: vertexCount }, (_, index) => index);
    const find = (value) => {
        let current = value;
        while (parents[current] !== current) {
            parents[current] = parents[parents[current]];
            current = parents[current];
        }
        return current;
    };
    const union = (a, b) => {
        const rootA = find(a);
        const rootB = find(b);
        if (rootA !== rootB) parents[rootB] = rootA;
    };

    for (let index = 0; index < geometry.indices.length; index += 3) {
        union(geometry.indices[index], geometry.indices[index + 1]);
        union(geometry.indices[index], geometry.indices[index + 2]);
    }

    const components = new Map();
    for (let vertex = 0; vertex < vertexCount; vertex++) {
        const root = find(vertex);
        if (!components.has(root)) components.set(root, { vertices: new Set(), indices: [] });
        components.get(root).vertices.add(vertex);
    }
    for (let index = 0; index < geometry.indices.length; index += 3) {
        components.get(find(geometry.indices[index])).indices.push(
            geometry.indices[index],
            geometry.indices[index + 1],
            geometry.indices[index + 2],
        );
    }
    return [...components.values()].filter(component => component.indices.length >= 3);
}

function quantize(value) {
    return Math.round(value * 100_000) / 100_000;
}

function vertexKey(geometry, vertex) {
    return [
        quantize(geometry.positions[vertex * 3]),
        quantize(geometry.positions[vertex * 3 + 1]),
        quantize(geometry.positions[vertex * 3 + 2]),
    ].join(',');
}

function componentShapeHash(geometry, component) {
    const orderedVertices = [...component.vertices].sort((a, b) => a - b);
    const localVertexKeys = new Map(orderedVertices.map(vertex => [vertex, vertexKey(geometry, vertex)]));
    const triangles = [];
    for (let index = 0; index < component.indices.length; index += 3) {
        triangles.push([
            localVertexKeys.get(component.indices[index]),
            localVertexKeys.get(component.indices[index + 1]),
            localVertexKeys.get(component.indices[index + 2]),
        ].sort().join('|'));
    }
    triangles.sort();
    return createHash('sha256')
        .update([...localVertexKeys.values()].join('\n'))
        .update('\n--\n')
        .update(triangles.join('\n'))
        .digest('hex');
}

function componentGeometry(geometry, component) {
    const orderedVertices = [...component.vertices].sort((a, b) => a - b);
    const remap = new Map(orderedVertices.map((vertex, index) => [vertex, index]));
    const positions = [];
    const normals = [];
    const bounds = {
        min: [Infinity, Infinity, Infinity],
        max: [-Infinity, -Infinity, -Infinity],
    };
    for (const vertex of orderedVertices) {
        for (let axis = 0; axis < 3; axis++) {
            const position = geometry.positions[vertex * 3 + axis];
            positions.push(position);
            if (position < bounds.min[axis]) bounds.min[axis] = position;
            if (position > bounds.max[axis]) bounds.max[axis] = position;
        }
        normals.push(
            geometry.normals[vertex * 3],
            geometry.normals[vertex * 3 + 1],
            geometry.normals[vertex * 3 + 2],
        );
    }
    const indices = component.indices.map(vertex => remap.get(vertex));
    return { positions, normals, indices, bounds };
}

function padLength(length) {
    return (4 - (length % 4)) % 4;
}

function padBuffer(buffer) {
    const padding = padLength(buffer.length);
    if (padding === 0) return buffer;
    return Buffer.concat([buffer, Buffer.alloc(padding)]);
}

function floatBuffer(values) {
    const buffer = Buffer.allocUnsafe(values.length * 4);
    for (let index = 0; index < values.length; index++) buffer.writeFloatLE(values[index], index * 4);
    return buffer;
}

function indexBuffer(indices, componentType) {
    const bytesPerIndex = componentType === COMPONENT_UNSIGNED_SHORT ? 2 : 4;
    const buffer = Buffer.allocUnsafe(indices.length * bytesPerIndex);
    for (let index = 0; index < indices.length; index++) {
        if (componentType === COMPONENT_UNSIGNED_SHORT) buffer.writeUInt16LE(indices[index], index * bytesPerIndex);
        else buffer.writeUInt32LE(indices[index], index * bytesPerIndex);
    }
    return buffer;
}

function packComponent(geometry, byteOffset = 0) {
    const componentType = geometry.positions.length / 3 <= 65_535 ? COMPONENT_UNSIGNED_SHORT : COMPONENT_UNSIGNED_INT;
    const indices = indexBuffer(geometry.indices, componentType);
    const positions = floatBuffer(geometry.positions);
    const normals = floatBuffer(geometry.normals);
    const indexOffset = byteOffset;
    const positionOffset = indexOffset + padBuffer(indices).length;
    const normalOffset = positionOffset + padBuffer(positions).length;
    const buffer = Buffer.concat([padBuffer(indices), padBuffer(positions), padBuffer(normals)]);
    return {
        buffer,
        meta: {
            indexByteOffset: indexOffset,
            indexByteLength: indices.length,
            positionByteOffset: positionOffset,
            positionByteLength: positions.length,
            normalByteOffset: normalOffset,
            normalByteLength: normals.length,
            indexComponentType: componentType,
            indexCount: geometry.indices.length,
            vertexCount: geometry.positions.length / 3,
            min: geometry.bounds.min,
            max: geometry.bounds.max,
        },
    };
}

function sharedPathForHash(hash) {
    return resolve(SHARED_COMPONENT_DIR, hash.slice(0, 2), `${hash}.bin`);
}

function writeSharedComponents(repeatedGroups, geometryByHash, apply) {
    const shared = new Map();
    for (const hash of repeatedGroups) {
        const geometry = geometryByHash.get(hash);
        const { buffer, meta } = packComponent(geometry);
        const path = sharedPathForHash(hash);
        shared.set(hash, { path, byteLength: buffer.length, meta });
        if (apply) {
            mkdirSync(dirname(path), { recursive: true });
            writeFileSync(path, buffer);
        }
    }
    return shared;
}

function buildPartBuffers(part, repeatedGroups, sharedComponents, apply) {
    const gltfPath = part.oldPath.replace(/\.glb$/i, '.gltf');
    const localBinPath = part.oldPath.replace(/\.glb$/i, '.bin');
    const uniqueComponents = [];
    const sharedHashes = [];
    const seenHashes = new Set();
    for (const component of part.components) {
        if (seenHashes.has(component.hash)) continue;
        seenHashes.add(component.hash);
        if (repeatedGroups.has(component.hash)) sharedHashes.push(component.hash);
        else uniqueComponents.push(component.geometry);
    }

    const buffers = [];
    const bufferViews = [];
    const accessors = [];
    const primitives = [];
    let localBinBytes = 0;

    function addPackedComponent(bufferIndex, meta) {
        const indexView = bufferViews.push({
            buffer: bufferIndex,
            byteOffset: meta.indexByteOffset,
            byteLength: meta.indexByteLength,
            target: 34963,
        }) - 1;
        const positionView = bufferViews.push({
            buffer: bufferIndex,
            byteOffset: meta.positionByteOffset,
            byteLength: meta.positionByteLength,
            target: 34962,
        }) - 1;
        const normalView = bufferViews.push({
            buffer: bufferIndex,
            byteOffset: meta.normalByteOffset,
            byteLength: meta.normalByteLength,
            target: 34962,
        }) - 1;
        const indexAccessor = accessors.push({
            bufferView: indexView,
            componentType: meta.indexComponentType,
            count: meta.indexCount,
            type: 'SCALAR',
        }) - 1;
        const positionAccessor = accessors.push({
            bufferView: positionView,
            componentType: COMPONENT_FLOAT,
            count: meta.vertexCount,
            type: 'VEC3',
            min: meta.min,
            max: meta.max,
        }) - 1;
        const normalAccessor = accessors.push({
            bufferView: normalView,
            componentType: COMPONENT_FLOAT,
            count: meta.vertexCount,
            type: 'VEC3',
        }) - 1;
        primitives.push({
            attributes: {
                POSITION: positionAccessor,
                NORMAL: normalAccessor,
            },
            indices: indexAccessor,
            mode: 4,
        });
    }

    for (const hash of sharedHashes) {
        const shared = sharedComponents.get(hash);
        const bufferIndex = buffers.push({
            uri: relativeUri(gltfPath, shared.path),
            byteLength: shared.byteLength,
        }) - 1;
        addPackedComponent(bufferIndex, shared.meta);
    }

    if (uniqueComponents.length > 0) {
        let byteOffset = 0;
        const chunks = [];
        const metas = [];
        for (const geometry of uniqueComponents) {
            const packed = packComponent(geometry, byteOffset);
            chunks.push(packed.buffer);
            metas.push(packed.meta);
            byteOffset += packed.buffer.length;
        }
        const localBuffer = Buffer.concat(chunks);
        localBinBytes = localBuffer.length;
        const bufferIndex = buffers.push({
            uri: basename(localBinPath),
            byteLength: localBuffer.length,
        }) - 1;
        for (const meta of metas) addPackedComponent(bufferIndex, meta);
        if (apply) writeFileSync(localBinPath, localBuffer);
    } else if (apply && existsSync(localBinPath)) {
        unlinkSync(localBinPath);
    }

    const gltf = {
        asset: {
            version: '2.0',
            generator: 'microscope_builder_4 scripts/catalog/dedupe-mounted-lens-housings.mjs',
        },
        scene: 0,
        scenes: [{ nodes: [0] }],
        nodes: [{ mesh: 0 }],
        meshes: [{ primitives }],
        buffers,
        bufferViews,
        accessors,
    };

    const gltfText = `${JSON.stringify(gltf)}\n`;
    if (apply) writeFileSync(gltfPath, gltfText);
    return {
        gltfPath,
        localBinPath,
        gltfBytes: Buffer.byteLength(gltfText),
        localBinBytes,
    };
}

function formatMb(bytes) {
    return `${(bytes / 1024 / 1024).toFixed(2)} MB`;
}

async function main() {
    if (hasFlag('--help')) {
        usage();
        return;
    }
    const apply = hasFlag('--apply');
    const keepGlb = hasFlag('--keep-glb');
    const manifestPath = resolve(argValue('--manifest', DEFAULT_MANIFEST));
    const assets = parseManifest(manifestPath);
    const lensAssets = assets.filter(isMountedLensGlbAsset);
    const uniqueLensAssets = [...new Map(lensAssets.map(asset => [asset.url, asset])).values()];
    if (uniqueLensAssets.length === 0) {
        console.log('No mounted lens GLB assets found to deduplicate.');
        return;
    }

    const parts = [];
    const groupStats = new Map();
    const geometryByHash = new Map();
    let originalBytes = 0;
    let componentInstances = 0;
    for (const asset of uniqueLensAssets) {
        const oldPath = assetPath(asset);
        originalBytes += statSync(oldPath).size;
        const geometry = parseGlb(oldPath);
        const components = [];
        for (const component of connectedComponents(geometry)) {
            const hash = componentShapeHash(geometry, component);
            const componentData = componentGeometry(geometry, component);
            components.push({ hash, geometry: componentData });
            geometryByHash.set(hash, componentData);
            const stats = groupStats.get(hash) ?? { count: 0, files: new Set() };
            stats.count++;
            stats.files.add(asset.url);
            groupStats.set(hash, stats);
            componentInstances++;
        }
        parts.push({ asset, oldPath, components });
    }

    const repeatedGroups = new Set(
        [...groupStats.entries()]
            .filter(([, stats]) => stats.files.size > 1)
            .map(([hash]) => hash),
    );
    const duplicatedInsidePartOnly = [...groupStats.values()]
        .filter(stats => stats.count > 1 && stats.files.size === 1)
        .reduce((sum, stats) => sum + stats.count - 1, 0);

    if (apply) {
        const sharedRoot = assertInside(SHARED_COMPONENT_DIR, PUBLIC_ROOT, 'shared component directory');
        if (existsSync(sharedRoot)) rmSync(sharedRoot, { recursive: true, force: true });
        mkdirSync(sharedRoot, { recursive: true });
    }

    const sharedComponents = writeSharedComponents(repeatedGroups, geometryByHash, apply);
    const updatedAssets = [...assets];
    const gltfOutputs = [];
    for (const part of parts) {
        const output = buildPartBuffers(part, repeatedGroups, sharedComponents, apply);
        gltfOutputs.push(output);
        const updated = {
            ...part.asset,
            format: 'gltf',
            url: publicPathToUrl(output.gltfPath),
        };
        for (let index = 0; index < updatedAssets.length; index++) {
            if (updatedAssets[index].url === part.asset.url) updatedAssets[index] = {
                ...updatedAssets[index],
                format: updated.format,
                url: updated.url,
            };
        }
        if (apply && !keepGlb && existsSync(part.oldPath)) unlinkSync(part.oldPath);
    }

    if (apply) {
        updatedAssets.sort((a, b) => a.sku.localeCompare(b.sku));
        writeFileReplacingMappedFile(manifestPath, manifestSource(updatedAssets));
    }

    const sharedBytes = [...sharedComponents.values()].reduce((sum, item) => sum + item.byteLength, 0);
    const gltfBytes = gltfOutputs.reduce((sum, output) => sum + output.gltfBytes, 0);
    const localBytes = gltfOutputs.reduce((sum, output) => sum + output.localBinBytes, 0);
    const generatedBytes = sharedBytes + gltfBytes + localBytes;

    console.log(`${apply ? 'Deduplicated' : 'Dry run analyzed'} ${uniqueLensAssets.length} mounted lens source asset(s) referenced by ${lensAssets.length} catalog entr${lensAssets.length === 1 ? 'y' : 'ies'}.`);
    console.log(`Connected components: ${componentInstances}; shared across lens files: ${repeatedGroups.size}; same-file duplicate instances removed: ${duplicatedInsidePartOnly}.`);
    console.log(`Original mounted lens GLB size: ${formatMb(originalBytes)}.`);
    console.log(`${apply ? 'New' : 'Estimated'} mounted lens GLTF/bin size: ${formatMb(generatedBytes)} (${formatMb(sharedBytes)} shared, ${formatMb(localBytes)} per-part binary, ${formatMb(gltfBytes)} GLTF JSON).`);
    console.log(`${apply ? 'Saved' : 'Would save'} ${formatMb(originalBytes - generatedBytes)} from mounted lens assets.`);
}

main().catch(error => {
    console.error(error instanceof Error ? error.stack ?? error.message : error);
    process.exitCode = 1;
});
