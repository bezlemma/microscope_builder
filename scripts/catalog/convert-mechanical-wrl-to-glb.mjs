import { createHash } from 'node:crypto';
import {
    existsSync,
    mkdirSync,
    readFileSync,
    renameSync,
    statSync,
    unlinkSync,
    writeFileSync,
} from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const PUBLIC_ROOT = resolve(ROOT, 'public');
const DEFAULT_MANIFEST = resolve(ROOT, 'src', 'catalog', 'generatedMechanicalVisualAssets.ts');
const GLB_MAGIC = 0x46546c67;
const GLB_JSON_CHUNK = 0x4e4f534a;
const GLB_BIN_CHUNK = 0x004e4942;
const COMPONENT_FLOAT = 5126;
const COMPONENT_UNSIGNED_SHORT = 5123;
const COMPONENT_UNSIGNED_INT = 5125;

function argValue(flag, fallback) {
    const index = process.argv.indexOf(flag);
    return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

function hasFlag(flag) {
    return process.argv.includes(flag);
}

function usage() {
    console.log(`Usage: bun scripts/catalog/convert-mechanical-wrl-to-glb.mjs [options]

Converts generated non-objective catalog WRL meshes into compact binary GLB
meshes, updates the generated manifest, and exact-deduplicates identical GLB
files by pointing repeated manifest entries at one shared asset.

Options:
  --apply            Write GLB files, delete replaced WRLs, and update manifest
  --manifest PATH    Generated mechanical visual manifest
  --keep-wrl         Keep converted WRL files after --apply
  --help             Show this help
`);
}

function parseManifest(manifestPath) {
    const text = readFileSync(manifestPath, 'utf8');
    const match = text.match(/=\s*(\{[\s\S]*\});?\s*$/);
    if (!match) throw new Error(`Could not parse manifest: ${manifestPath}`);
    return Object.values(JSON.parse(match[1]));
}

function manifestSource(assets) {
    const rows = Object.fromEntries(assets.map(asset => [asset.partId, asset]));
    return `import type { CatalogMechanicalVisualAsset } from './mechanicalVisualAssets';

// Generated by scripts/catalog/build-objective-mechanical-assets.mjs.
// The app renders vendor mechanical assets listed here; STEP URLs in the
// catalog remain source CAD and are converted offline into browser-loadable meshes.
export const GENERATED_MECHANICAL_VISUAL_ASSETS: Record<string, CatalogMechanicalVisualAsset> = ${JSON.stringify(rows, null, 4)};
`;
}

function writeFileReplacingMappedFile(path, text) {
    try {
        writeFileSync(path, text);
        return;
    } catch (error) {
        if (error?.code !== 'UNKNOWN' && error?.code !== 'EPERM' && error?.code !== 'EBUSY') throw error;
    }

    const nextPath = `${path}.new`;
    const backupPath = `${path}.mapped-backup`;
    writeFileSync(nextPath, text);
    if (existsSync(backupPath)) unlinkSync(backupPath);
    renameSync(path, backupPath);
    renameSync(nextPath, path);
    try {
        unlinkSync(backupPath);
    } catch {
        // The backup is only a fallback for Windows file mapping races.
    }
}

function assertInside(path, root, label) {
    const resolvedPath = resolve(path);
    const resolvedRoot = resolve(root);
    if (resolvedPath !== resolvedRoot && !resolvedPath.startsWith(`${resolvedRoot}\\`) && !resolvedPath.startsWith(`${resolvedRoot}/`)) {
        throw new Error(`Refusing to touch ${label} outside ${resolvedRoot}: ${resolvedPath}`);
    }
    return resolvedPath;
}

function assetPath(asset) {
    if (!asset.url.startsWith('/')) throw new Error(`Mechanical asset URL must be root-relative: ${asset.url}`);
    return assertInside(resolve(PUBLIC_ROOT, `.${asset.url}`), PUBLIC_ROOT, 'asset');
}

function urlToPublicPath(url) {
    if (!url.startsWith('/')) throw new Error(`Mechanical asset URL must be root-relative: ${url}`);
    return assertInside(resolve(PUBLIC_ROOT, `.${url}`), PUBLIC_ROOT, 'asset');
}

function publicPathToUrl(path) {
    const resolved = assertInside(path, PUBLIC_ROOT, 'asset');
    const relative = resolved.slice(PUBLIC_ROOT.length).replace(/\\/g, '/').replace(/^\//, '');
    return `/${relative}`;
}

function isConvertibleWrlAsset(asset) {
    return (
        asset.format === 'wrl' &&
        !asset.url.includes('/objectives/') &&
        (asset.url.includes('/catalog/mechanical/lenses/') || asset.url.includes('/catalog/mechanical/fold-optics/'))
    );
}

function numberTokens(text) {
    return text.match(/[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?/g) ?? [];
}

function parseWrlGeometry(path) {
    const text = readFileSync(path, 'utf8');
    const pointBlocks = [...text.matchAll(/\bpoint\s*\[([\s\S]*?)\]/g)];
    const indexBlocks = [...text.matchAll(/\bcoordIndex\s*\[([\s\S]*?)\]/g)];
    if (pointBlocks.length === 0 || indexBlocks.length === 0) {
        throw new Error(`WRL mesh is missing Coordinate/coordIndex data: ${path}`);
    }

    const positions = [];
    const triangles = [];
    const blockCount = Math.min(pointBlocks.length, indexBlocks.length);
    for (let blockIndex = 0; blockIndex < blockCount; blockIndex++) {
        const offset = positions.length / 3;
        const pointValues = numberTokens(pointBlocks[blockIndex][1]);
        for (let index = 0; index + 2 < pointValues.length; index += 3) {
            positions.push(
                Number(pointValues[index]),
                Number(pointValues[index + 1]),
                Number(pointValues[index + 2]),
            );
        }

        const indexValues = (indexBlocks[blockIndex][1].match(/-?\d+/g) ?? []).map(value => Number.parseInt(value, 10));
        let face = [];
        for (const value of indexValues) {
            if (value === -1) {
                triangulateFace(face, offset, triangles);
                face = [];
                continue;
            }
            face.push(value);
        }
        triangulateFace(face, offset, triangles);
    }

    if (positions.length === 0 || triangles.length === 0) {
        throw new Error(`WRL mesh has no renderable triangles: ${path}`);
    }
    return { positions, triangles };
}

function triangulateFace(face, offset, triangles) {
    if (face.length < 3) return;
    for (let index = 1; index + 1 < face.length; index++) {
        triangles.push(offset + face[0], offset + face[index], offset + face[index + 1]);
    }
}

function computeBounds(positions) {
    const min = [Infinity, Infinity, Infinity];
    const max = [-Infinity, -Infinity, -Infinity];
    for (let index = 0; index + 2 < positions.length; index += 3) {
        for (let axis = 0; axis < 3; axis++) {
            const value = positions[index + axis];
            if (value < min[axis]) min[axis] = value;
            if (value > max[axis]) max[axis] = value;
        }
    }
    return { min, max };
}

function computeNormals(positions, triangles) {
    const normals = new Array(positions.length).fill(0);
    for (let index = 0; index + 2 < triangles.length; index += 3) {
        const a = triangles[index] * 3;
        const b = triangles[index + 1] * 3;
        const c = triangles[index + 2] * 3;
        const abx = positions[b] - positions[a];
        const aby = positions[b + 1] - positions[a + 1];
        const abz = positions[b + 2] - positions[a + 2];
        const acx = positions[c] - positions[a];
        const acy = positions[c + 1] - positions[a + 1];
        const acz = positions[c + 2] - positions[a + 2];
        const nx = aby * acz - abz * acy;
        const ny = abz * acx - abx * acz;
        const nz = abx * acy - aby * acx;
        for (const vertex of [a, b, c]) {
            normals[vertex] += nx;
            normals[vertex + 1] += ny;
            normals[vertex + 2] += nz;
        }
    }
    for (let index = 0; index + 2 < normals.length; index += 3) {
        const length = Math.hypot(normals[index], normals[index + 1], normals[index + 2]);
        if (length > 1e-12) {
            normals[index] /= length;
            normals[index + 1] /= length;
            normals[index + 2] /= length;
        } else {
            normals[index + 2] = 1;
        }
    }
    return normals;
}

function padBuffer(buffer, byte = 0) {
    const padding = (4 - (buffer.length % 4)) % 4;
    if (padding === 0) return buffer;
    return Buffer.concat([buffer, Buffer.alloc(padding, byte)]);
}

function typedBufferFromFloats(values) {
    const buffer = Buffer.allocUnsafe(values.length * 4);
    for (let index = 0; index < values.length; index++) buffer.writeFloatLE(values[index], index * 4);
    return buffer;
}

function typedBufferFromIndices(indices, componentType) {
    const bytesPerIndex = componentType === COMPONENT_UNSIGNED_SHORT ? 2 : 4;
    const buffer = Buffer.allocUnsafe(indices.length * bytesPerIndex);
    for (let index = 0; index < indices.length; index++) {
        if (componentType === COMPONENT_UNSIGNED_SHORT) buffer.writeUInt16LE(indices[index], index * bytesPerIndex);
        else buffer.writeUInt32LE(indices[index], index * bytesPerIndex);
    }
    return buffer;
}

function makeGlbBuffer(geometry) {
    const vertexCount = geometry.positions.length / 3;
    const componentType = vertexCount <= 65_535 ? COMPONENT_UNSIGNED_SHORT : COMPONENT_UNSIGNED_INT;
    const bounds = computeBounds(geometry.positions);
    const normals = computeNormals(geometry.positions, geometry.triangles);
    const indexBuffer = padBuffer(typedBufferFromIndices(geometry.triangles, componentType));
    const positionBuffer = padBuffer(typedBufferFromFloats(geometry.positions));
    const normalBuffer = padBuffer(typedBufferFromFloats(normals));

    const indexOffset = 0;
    const positionOffset = indexOffset + indexBuffer.length;
    const normalOffset = positionOffset + positionBuffer.length;
    const bin = Buffer.concat([indexBuffer, positionBuffer, normalBuffer]);
    const gltf = {
        asset: {
            version: '2.0',
            generator: 'microscope_builder_4 scripts/catalog/convert-mechanical-wrl-to-glb.mjs',
        },
        scene: 0,
        scenes: [{ nodes: [0] }],
        nodes: [{ mesh: 0 }],
        meshes: [{
            primitives: [{
                attributes: { POSITION: 1, NORMAL: 2 },
                indices: 0,
                mode: 4,
            }],
        }],
        buffers: [{ byteLength: bin.length }],
        bufferViews: [
            {
                buffer: 0,
                byteOffset: indexOffset,
                byteLength: geometry.triangles.length * (componentType === COMPONENT_UNSIGNED_SHORT ? 2 : 4),
                target: 34963,
            },
            {
                buffer: 0,
                byteOffset: positionOffset,
                byteLength: geometry.positions.length * 4,
                target: 34962,
            },
            {
                buffer: 0,
                byteOffset: normalOffset,
                byteLength: normals.length * 4,
                target: 34962,
            },
        ],
        accessors: [
            {
                bufferView: 0,
                componentType,
                count: geometry.triangles.length,
                type: 'SCALAR',
            },
            {
                bufferView: 1,
                componentType: COMPONENT_FLOAT,
                count: vertexCount,
                type: 'VEC3',
                min: bounds.min,
                max: bounds.max,
            },
            {
                bufferView: 2,
                componentType: COMPONENT_FLOAT,
                count: vertexCount,
                type: 'VEC3',
            },
        ],
    };

    const json = padBuffer(Buffer.from(JSON.stringify(gltf), 'utf8'), 0x20);
    const totalLength = 12 + 8 + json.length + 8 + bin.length;
    const output = Buffer.allocUnsafe(totalLength);
    let offset = 0;
    output.writeUInt32LE(GLB_MAGIC, offset); offset += 4;
    output.writeUInt32LE(2, offset); offset += 4;
    output.writeUInt32LE(totalLength, offset); offset += 4;
    output.writeUInt32LE(json.length, offset); offset += 4;
    output.writeUInt32LE(GLB_JSON_CHUNK, offset); offset += 4;
    json.copy(output, offset); offset += json.length;
    output.writeUInt32LE(bin.length, offset); offset += 4;
    output.writeUInt32LE(GLB_BIN_CHUNK, offset); offset += 4;
    bin.copy(output, offset);
    return {
        buffer: output,
        vertexCount,
        triangleCount: geometry.triangles.length / 3,
    };
}

function fileHash(path) {
    return createHash('sha256').update(readFileSync(path)).digest('hex');
}

function hashBuffer(buffer) {
    return createHash('sha256').update(buffer).digest('hex');
}

function formatMb(bytes) {
    return `${(bytes / 1024 / 1024).toFixed(2)} MB`;
}

async function main() {
    if (hasFlag('--help')) {
        usage();
        return;
    }

    const apply = hasFlag('--apply');
    const keepWrl = hasFlag('--keep-wrl');
    const manifestPath = resolve(argValue('--manifest', DEFAULT_MANIFEST));
    const assets = parseManifest(manifestPath);
    const converted = [];
    const updatedAssets = [];

    for (const asset of assets) {
        if (!isConvertibleWrlAsset(asset)) {
            updatedAssets.push(asset);
            continue;
        }

        const oldPath = assetPath(asset);
        if (!existsSync(oldPath)) throw new Error(`Missing generated WRL asset: ${oldPath}`);
        const glbPath = oldPath.replace(/\.wrl$/i, '.glb');
        const glbUrl = publicPathToUrl(glbPath);
        const geometry = parseWrlGeometry(oldPath);
        const { buffer, vertexCount, triangleCount } = makeGlbBuffer(geometry);
        const oldSize = statSync(oldPath).size;
        const hash = hashBuffer(buffer);

        if (apply) {
            mkdirSync(dirname(glbPath), { recursive: true });
            const tempPath = `${glbPath}.tmp`;
            writeFileSync(tempPath, buffer);
            renameSync(tempPath, glbPath);
        }

        const nextAsset = {
            ...asset,
            format: 'glb',
            url: glbUrl,
        };
        updatedAssets.push(nextAsset);
        converted.push({
            asset: nextAsset,
            oldPath,
            oldUrl: asset.url,
            glbPath,
            oldSize,
            newSize: buffer.length,
            hash,
            vertexCount,
            triangleCount,
        });
    }

    const canonicalByHash = new Map();
    const duplicateFiles = [];
    let deduplicatedCount = 0;
    for (const conversion of converted) {
        const hash = apply ? fileHash(conversion.glbPath) : conversion.hash;
        const canonical = canonicalByHash.get(hash);
        if (!canonical) {
            canonicalByHash.set(hash, conversion);
            continue;
        }
        conversion.asset.url = canonical.asset.url;
        deduplicatedCount++;
        if (conversion.glbPath !== canonical.glbPath) duplicateFiles.push(conversion.glbPath);
    }

    const oldBytes = converted.reduce((sum, conversion) => sum + conversion.oldSize, 0);
    const rawGlbBytes = converted.reduce((sum, conversion) => sum + conversion.newSize, 0);

    if (apply) {
        for (const path of duplicateFiles) {
            if (existsSync(path)) unlinkSync(path);
        }
        if (!keepWrl) {
            for (const conversion of converted) {
                if (existsSync(conversion.oldPath)) unlinkSync(conversion.oldPath);
            }
        }
        updatedAssets.sort((a, b) => a.sku.localeCompare(b.sku));
        writeFileReplacingMappedFile(manifestPath, manifestSource(updatedAssets));
    }

    let uniqueGlbBytes = 0;
    const counted = new Set();
    for (const conversion of converted) {
        const url = conversion.asset.url;
        if (counted.has(url)) continue;
        counted.add(url);
        uniqueGlbBytes += apply ? statSync(urlToPublicPath(url)).size : conversion.newSize;
    }

    console.log(`${apply ? 'Converted' : 'Dry run converted'} ${converted.length} non-objective WRL asset(s) to GLB.`);
    console.log(`Raw size: ${formatMb(oldBytes)} WRL -> ${formatMb(rawGlbBytes)} GLB before dedupe.`);
    console.log(`Exact dedupe: ${deduplicatedCount} duplicate manifest entr${deduplicatedCount === 1 ? 'y' : 'ies'}, ${formatMb(rawGlbBytes - uniqueGlbBytes)} saved.`);
    console.log(`Unique GLB size: ${formatMb(uniqueGlbBytes)}.`);
}

main().catch(error => {
    console.error(error instanceof Error ? error.stack ?? error.message : error);
    process.exitCode = 1;
});
